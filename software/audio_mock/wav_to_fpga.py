#!/usr/bin/env python3
"""Convert a PCM WAV file into the ROM files used by the FPGA mock player."""

import argparse
import pathlib
import struct
import wave


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=pathlib.Path)
    parser.add_argument("--mem", type=pathlib.Path,
                        default=pathlib.Path("rtl/top/audio_mock.mem"))
    parser.add_argument("--config", type=pathlib.Path,
                        default=pathlib.Path("rtl/top/audio_mock_config.svh"))
    parser.add_argument("--max-seconds", type=float, default=1.0,
                        help="limita o tamanho da ROM (padrão: 1 segundo)")
    args = parser.parse_args()

    with wave.open(str(args.input), "rb") as source:
        channels = source.getnchannels()
        width = source.getsampwidth()
        rate = source.getframerate()
        frames = source.getnframes()
        if width != 2:
            raise SystemExit("erro: o WAV deve ser PCM signed 16-bit")
        if channels not in (1, 2):
            raise SystemExit("erro: o WAV deve ser mono ou estéreo")
        max_frames = min(frames, int(rate * args.max_seconds))
        raw = source.readframes(max_frames)

    values = list(struct.unpack("<%dh" % (len(raw) // 2), raw))
    args.mem.parent.mkdir(parents=True, exist_ok=True)
    args.config.parent.mkdir(parents=True, exist_ok=True)
    args.mem.write_text("\n".join(f"{value & 0xffff:04x}" for value in values) + "\n")
    args.config.write_text(
        "// Generated by software/audio_mock/wav_to_fpga.py.\n"
        f"localparam int unsigned AUDIO_MOCK_SAMPLE_COUNT = {len(values)};\n"
    )
    print(f"WAV: {args.input}")
    print(f"canais={channels} taxa={rate} Hz amostras={len(values)}")
    print(f"ROM: {args.mem} / configuração: {args.config}")
    if channels == 2:
        print("O estéreo permanece intercalado: L0, R0, L1, R1, ...")


if __name__ == "__main__":
    main()
